import frappe
from frappe.model.document import Document
from frappe.utils import getdate, nowdate, format_date


class EgpOpportunities(Document):
	pass


@frappe.whitelist()
def send_upcoming_egp_opportunities():
    # Get all opportunities with closing date >= today, sorted by closing_date
    opportunities = frappe.db.sql("""
        SELECT 
            `id`,
            `link`,
            `title`,
            `entity`,
            `tender_reference_number`,
            `status`,
            `bid_submission_status`,
            `closing_date`
        FROM 
            `tabEgp Opportunities`
        
        ORDER BY 
            `closing_date` ASC
    """, {'today': nowdate()}, as_dict=True)

    if not opportunities:
        frappe.msgprint("No upcoming opportunities found")
        return

    # Prepare HTML table rows
    table_rows = ""
    for opp in opportunities:
        table_rows += f"""
        <tr>
            <td><a href="{opp.link}" target="_blank">{opp.id}</a></td>
            <td>{opp.title}</td>
            <td>{opp.tender_reference_number}</td>
            <td>{opp.entity}</td>
            <td>{opp.status}</td>
            <td>{opp.bid_submission_status}</td>
            <td>{format_date(opp.closing_date)}</td>
        </tr>
        """

    # Prepare email message
    html_message = f"""
    <html>
    <head>
    <style>
        body {{ font-family: Arial, sans-serif; line-height: 1.6; }}
        .header {{ color: #2c3e50; font-size: 18px; font-weight: bold; margin-bottom: 20px; }}
        .subheader {{ color: #7f8c8d; margin-bottom: 15px; }}
        table {{ 
            width: 100%; 
            border-collapse: collapse;
            margin: 15px 0;
        }}
        th {{
            background-color: #3498db;
            color: white;
            text-align: left;
            padding: 10px;
        }}
        td {{
            padding: 8px 10px;
            border-bottom: 1px solid #ddd;
        }}
        tr:nth-child(even) {{ background-color: #f2f2f2; }}
        .link {{ color: #0275d8; text-decoration: none; }}
        .count {{ font-weight: bold; color: #e74c3c; }}
    </style>
    </head>
    <body>
        <div class="header">📅 Upcoming EGP Opportunities</div>
        <div class="subheader">Found <span class="count">{len(opportunities)}</span> opportunities closing soon</div>
        
        <table>
            <thead>
                <tr>
                    <th>Tender ID</th>
                    <th>Title</th>
                    <th>Tender Reference Number</th>
                    <th>Entity</th>
                    <th>Status of Bid notice</th>
                    <th>Bid Submission Status</th>
                    <th>Closing Date</th>
                </tr>
            </thead>
            <tbody>
                {table_rows}
            </tbody>
        </table>
        
        <div style="margin-top: 20px; font-size: 12px; color: #7f8c8d;">
            This email was automatically generated by the system.
        </div>
    </body>
    </html>
    """

    # set "tender_digest_recipient" in site_config.json
    recipient = frappe.conf.get("tender_digest_recipient") or "sales@example.com"
    subject = f"Upcoming EGP Opportunities For Zimbabwe."

    # Send email
    frappe.sendmail(
        recipients=[recipient],
        subject=subject,
        message=html_message,
    )

    print(f"Email sent to {recipient} with {len(opportunities)} opportunities")