import json

import frappe
from frappe.model.document import Document
from frappe.utils import getdate, nowdate, format_date


# Default UNSPSC category codes used to seed Eprocure Settings.unspsc_codes (via
# the init_unspsc_codes patch) and as a fallback when that field is empty. An example
# set for an IT business; edit the codes in Eprocure Settings for your own.
DEFAULT_UNSPSC_CODES = [
	"43211500",  # computers
	"43222600",  # network equipment
	"81111800",  # computer services
	"86132000",  # training and certification
]


class EprocureSettings(Document):
	def get_unspsc_codes(self):
		"""UNSPSC codes from the ``unspsc_codes`` JSON field.

		Falls back to DEFAULT_UNSPSC_CODES when the field is empty, unset or
		invalid (e.g. before the init_unspsc_codes patch has run). Frappe may hand
		back the JSON field as a parsed list or as a raw string depending on how
		the doc was loaded, so we handle both.
		"""
		raw = self.unspsc_codes
		if isinstance(raw, str):
			raw = raw.strip()
			try:
				raw = json.loads(raw) if raw else None
			except (ValueError, TypeError):
				raw = None
		if isinstance(raw, list) and raw:
			return [str(c).strip() for c in raw if str(c).strip()]
		return list(DEFAULT_UNSPSC_CODES)


@frappe.whitelist()
def send_upcoming_zambia_opportunities():
    # Get all opportunities with submission_deadline >= today, sorted by deadline
    opportunities = frappe.db.sql("""
        SELECT 
            `name`,
            `tender_link`,
            `title`,
            `procuring_entity`,
            `reference_id`,
            `status`,
            `procedure`,
            `submission_deadline`
        FROM 
            `tabEprocure Tender`
        WHERE
            `submission_deadline` >= %(today)s
        ORDER BY 
            `submission_deadline` ASC
    """, {'today': nowdate()}, as_dict=True)

    if not opportunities:
        frappe.msgprint("No upcoming opportunities found")
        return

    # Prepare HTML table rows
    table_rows = ""
    for opp in opportunities:
        table_rows += f"""
        <tr>
            <td><a href="{opp.tender_link}" target="_blank">{opp.name}</a></td>
            <td>{opp.title}</td>
            <td>{opp.reference_id}</td>
            <td>{opp.procuring_entity}</td>
            <td>{opp.status}</td>
            <td>{opp.procedure}</td>
            <td>{format_date(opp.submission_deadline)}</td>
        </tr>
        """

    # Prepare email message
    html_message = f"""
    <html>
    <head>
    <style>
        body {{ font-family: Arial, sans-serif; line-height: 1.6; }}
        .header {{ color: #2c3e50; font-size: 18px; font-weight: bold; margin-bottom: 20px; }}
        .subheader {{ color: #7f8c8d; margin-bottom: 15px; }}
        table {{ 
            width: 100%; 
            border-collapse: collapse;
            margin: 15px 0;
        }}
        th {{
            background-color: #3498db;
            color: white;
            text-align: left;
            padding: 10px;
        }}
        td {{
            padding: 8px 10px;
            border-bottom: 1px solid #ddd;
        }}
        tr:nth-child(even) {{ background-color: #f2f2f2; }}
        .link {{ color: #0275d8; text-decoration: none; }}
        .count {{ font-weight: bold; color: #e74c3c; }}
    </style>
    </head>
    <body>
        <div class="header">📅 Upcoming Zambia Procurement Opportunities</div>
        <div class="subheader">Found <span class="count">{len(opportunities)}</span> opportunities closing soon</div>
        
        <table>
            <thead>
                <tr>
                    <th>Tender ID</th>
                    <th>Title</th>
                    <th>Reference ID</th>
                    <th>Procuring Entity</th>
                    <th>Status</th>
                    <th>Procedure</th>
                    <th>Submission Deadline</th>
                </tr>
            </thead>
            <tbody>
                {table_rows}
            </tbody>
        </table>
        
        <div style="margin-top: 20px; font-size: 12px; color: #7f8c8d;">
            This email was automatically generated by the system.
        </div>
    </body>
    </html>
    """

    # set "tender_digest_recipient" in site_config.json
    recipient = frappe.conf.get("tender_digest_recipient") or "sales@example.com"
    subject = f"Upcoming Zambia Procurement Opportunities"

    # Send email
    frappe.sendmail(
        recipients=[recipient],
        subject=subject,
        message=html_message,
    )

    print(f"Email sent to {recipient} with {len(opportunities)} opportunities")